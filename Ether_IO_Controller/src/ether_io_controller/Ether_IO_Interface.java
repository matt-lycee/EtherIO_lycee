    private void trucled(){
        String concatenation ="";
        int[] tableauBin = new int[8];
        for(int i=0;i<cases.length;i++){
            if(cases[i].isSelected()){
                tableauBin[i]=1;
            }
            else{
                tableauBin[i]=0;
            }
            concatenation+= tableauBin[i];
        }
        
        int valeur = Integer.parseInt(concatenation, 2);
        System.out.println(valeur);
        
        EtherIO1.ecrirPort("A", valeur);
        
    }
    
